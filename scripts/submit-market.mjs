#!/usr/bin/env node
/**
 * Submit the generated marketplace artifacts through the GitHub API.
 *
 *   node scripts/submit-market.mjs status            # read-only: topics, issues, forks, PRs
 *   node scripts/submit-market.mjs topics  --apply   # add the dsh-plugin topic set
 *   node scripts/submit-market.mjs issues  --apply   # open the dsh-suite + dsh-plugin.org issues
 *   node scripts/submit-market.mjs fork-awesome      # fork + branch, no PR (the 24h age gate)
 *   node scripts/submit-market.mjs fork-alex --apply # fork + catalog entry + PR
 *
 * Without `--apply` every command only prints what it would do. The token comes
 * from `GH_TOKEN` or `~/.dsh-market-token` and is never printed. The artifacts
 * themselves come from `market/submissions/`, generated by `market:build`.
 */
import { readFileSync, existsSync } from 'node:fs'
import { homedir } from 'node:os'
import { join } from 'node:path'

const ROOT = process.cwd()
const listing = JSON.parse(readFileSync(join(ROOT, 'market/listing.json'), 'utf8'))
const submissions = join(ROOT, 'market/submissions')
const slug = `${listing.author}/${listing.repository.split('/').at(-1)}`
const forkOwner = listing.author
const awesome = { repo: 'awesome-dsh-plugin/awesome-dsh-plugin', path: `data/plugins/${listing.author}__${listing.repository.split('/').at(-1)}.yml` }
const alex = { repo: 'Alex-Yanggg/awesome-DSH-plugin', path: 'catalog/plugins.json' }

const command = process.argv[2]
const apply = process.argv.includes('--apply')
const token = process.env.GH_TOKEN ?? readTokenFile()
if (!token) fail('no token: set GH_TOKEN or create ~/.dsh-market-token (see market/README.md)')

const api = makeApi(token)

switch (command) {
  case 'status':
    await status()
    break
  case 'topics':
    await topics()
    break
  case 'issues':
    await issues()
    break
  case 'fork-awesome':
    await submitAwesome()
    break
  case 'fork-alex':
    await submitAlex()
    break
  default:
    fail('usage: submit-market.mjs <status|topics|issues|fork-awesome|fork-alex> [--apply]')
}

// ---------------------------------------------------------------------------

async function status() {
  const repo = await api('GET', `/repos/${slug}`)
  const topics = (await api('GET', `/repos/${slug}/topics`)).data?.names ?? []
  console.log(`repo: ${slug} (${String(repo.data?.stargazers_count)} stars, topics: ${topics.join(', ') || 'none'})`)

  for (const [label, target, title] of [
    ['dsh-suite', 'whyihaveyou/dsh-suite', suiteTitle()],
    ['dsh-plugin.org', 'dshplugin/dsh-plugin-hub', hubTitle()],
  ]) {
    const found = await findIssue(target, title)
    console.log(`${label} issue: ${found ? `#${String(found.number)} ${found.html_url}` : 'not opened'}`)
  }

  for (const [label, target, branch] of [
    ['awesome-dsh-plugin', awesome.repo, `add-${listing.author}__${slug.split('/').at(-1)}`],
    ['awesome-DSH-plugin', alex.repo, `add-${slug.split('/').at(-1)}`],
  ]) {
    const prs = await api('GET', `/repos/${target}/pulls?head=${forkOwner}:${branch}&state=all`)
    console.log(`${label} PR: ${prs.ok && prs.data.length > 0 ? prs.data[0].html_url : `not opened (branch ${branch})`}`)
  }
  const age = await repoAgeHours()
  const gate = age < 24 ? `repo is ${age.toFixed(1)}h old; awesome-dsh-plugin opens at ${new Date(Date.parse(repo.data.created_at) + 86_400_000).toISOString()}` : 'repo age gate passed'
  console.log(`age: ${gate}`)
}

async function topics() {
  const names = ['dsh-plugin', 'dsh', 'deepseek-harness', 'translation', 'i18n', 'client-plugin']
  console.log(`PUT /repos/${slug}/topics ${names.join(', ')}`)
  if (!apply) return
  const result = await api('PUT', `/repos/${slug}/topics`, { names })
  if (!result.ok) fail(`topics failed: ${describeFailure(result)}`)
  console.log(`topics now: ${result.data.names.join(', ')}`)
}

async function issues() {
  const targets = [
    { label: 'dsh-suite', repo: 'whyihaveyou/dsh-suite', title: suiteTitle(), body: suiteBody(), labels: ['catalog'] },
    { label: 'dsh-plugin.org', repo: 'dshplugin/dsh-plugin-hub', title: hubTitle(), body: hubBody() },
  ]
  for (const target of targets) {
    const existing = await findIssue(target.repo, target.title)
    if (existing) {
      console.log(`${target.label}: already open at ${existing.html_url}`)
      continue
    }
    console.log(`POST /repos/${target.repo}/issues — ${target.title}`)
    if (!apply) continue
    const body = { title: target.title, body: target.body }
    const result = await api('POST', `/repos/${target.repo}/issues`, body)
    if (!result.ok) {
      console.error(`${target.label}: ${describeFailure(result)}`)
      continue
    }
    console.log(`${target.label}: ${result.data.html_url}`)
  }
}

async function submitAwesome() {
  const content = readFileSync(join(submissions, 'awesome-dsh-plugin.yml'), 'utf8')
  const branch = `add-${listing.author}__${slug.split('/').at(-1)}`
  console.log(`fork ${awesome.repo}; branch ${branch}; add ${awesome.path}`)
  if (!apply) return

  const baseBranch = await upstreamDefaultBranch(awesome.repo)
  const fork = await ensureFork(awesome.repo)
  const base = (await api('GET', `/repos/${fork}/git/ref/heads/${baseBranch}`)).data.object.sha
  await ensureBranch(fork, branch, base)
  const existing = await api('GET', `/repos/${fork}/contents/${awesome.path}?ref=${branch}`)
  if (existing.ok) {
    console.log(`file already committed on ${branch}: ${existing.data.html_url}`)
  } else {
    const result = await api('PUT', `/repos/${fork}/contents/${awesome.path}`, {
      message: `Add ${slug}`,
      content: Buffer.from(content, 'utf8').toString('base64'),
      branch,
    })
    if (!result.ok) fail(`commit failed: ${describeFailure(result)}`)
    console.log(`committed: ${result.data.commit.html_url}`)
  }

  // The list refuses repos younger than one day (R5), so a PR today would only
  // show failing CI. The branch is ready; the PR is opened once the gate opens.
  const ageHours = await repoAgeHours()
  if (ageHours < 24) {
    const compare = `https://github.com/${awesome.repo}/compare/${baseBranch}...${forkOwner}:${branch}?expand=1`
    console.log(`repo is ${ageHours.toFixed(1)}h old (<24h): PR deferred. Open it here once eligible:\n  ${compare}`)
    return
  }
  await openPullRequest(awesome.repo, branch, `Add ${slug}`, readFileSync(join(submissions, 'awesome-dsh-plugin-pr.md'), 'utf8'))
}

async function submitAlex() {
  const entry = JSON.parse(readFileSync(join(submissions, 'alex-yanggg-catalog-entry.json'), 'utf8'))
  const branch = `add-${listing.repository.split('/').at(-1)}`
  console.log(`fork ${alex.repo}; branch ${branch}; insert ${entry.name} into ${alex.path}`)
  if (!apply) return

  const baseBranch = await upstreamDefaultBranch(alex.repo)
  const fork = await ensureFork(alex.repo)
  const base = (await api('GET', `/repos/${fork}/git/ref/heads/${baseBranch}`)).data.object.sha
  await ensureBranch(fork, branch, base)
  const file = await api('GET', `/repos/${fork}/contents/${alex.path}?ref=${branch}`)
  if (!file.ok) fail(`cannot read ${alex.path} on ${branch}: ${describeFailure(file)}`)
  const original = Buffer.from(file.data.content, 'base64').toString('utf8')
  const updated = insertCatalogEntry(original, entry)
  if (updated === original) {
    console.log('entry already present; nothing to commit')
  } else {
    const result = await api('PUT', `/repos/${fork}/contents/${alex.path}`, {
      message: `Add ${entry.name}`,
      content: Buffer.from(updated, 'utf8').toString('base64'),
      branch,
      sha: file.data.sha,
    })
    if (!result.ok) fail(`commit failed: ${describeFailure(result)}`)
    console.log(`committed: ${result.data.commit.html_url}`)
  }
  await openPullRequest(alex.repo, branch, `Add ${entry.name} to UI & user experience`, readFileSync(join(submissions, 'alex-yanggg-pr.md'), 'utf8'))
}

/**
 * Insert one entry before the closing bracket of `plugins`, keeping the rest of
 * the document byte-identical (JSON.stringify would reformat 600 KiB of catalog).
 */
function insertCatalogEntry(text, entry) {
  const parsed = JSON.parse(text)
  if (parsed.plugins.some((plugin) => plugin.name === entry.name)) return text
  const marker = /\n {2}\]\n\}\s*$/u
  if (!marker.test(text)) fail('catalog layout changed: cannot find the plugins closing bracket')
  const record = JSON.stringify(entry, null, 2)
    .split('\n')
    .map((line) => `    ${line}`)
    .join('\n')
  const updated = text.replace(marker, `,\n${record}\n  ]\n}\n`)
  const reparsed = JSON.parse(updated)
  if (reparsed.plugins.at(-1)?.name !== entry.name) fail('catalog insert did not land as the last plugin')
  if (reparsed.plugins.length !== parsed.plugins.length + 1) fail('catalog insert changed the entry count')
  return updated
}

async function openPullRequest(repo, branch, title, body) {
  const prs = await api('GET', `/repos/${repo}/pulls?head=${forkOwner}:${branch}&state=all`)
  if (prs.ok && prs.data.length > 0) {
    console.log(`PR already exists: ${prs.data[0].html_url}`)
    return
  }
  const result = await api('POST', `/repos/${repo}/pulls`, { title, head: `${forkOwner}:${branch}`, base: await upstreamDefaultBranch(repo), body })
  if (!result.ok) fail(`PR failed: ${describeFailure(result)}`)
  console.log(`PR: ${result.data.html_url}`)
}

async function ensureFork(repo) {
  const name = repo.split('/').at(-1)
  const existing = await api('GET', `/repos/${forkOwner}/${name}`)
  if (existing.ok) return existing.data.full_name
  const created = await api('POST', `/repos/${repo}/forks`, { default_branch_only: false })
  if (!created.ok && created.status !== 202) fail(`fork failed: ${describeFailure(created)}`)
  for (let attempt = 0; attempt < 20; attempt += 1) {
    const ready = await api('GET', `/repos/${forkOwner}/${name}`)
    if (ready.ok) return ready.data.full_name
    await new Promise((resolve) => setTimeout(resolve, 3000))
  }
  fail(`fork ${repo} did not become ready`)
}

async function ensureBranch(repo, branch, sha) {
  const existing = await api('GET', `/repos/${repo}/git/ref/heads/${branch}`)
  if (existing.ok) return
  const created = await api('POST', `/repos/${repo}/git/refs`, { ref: `refs/heads/${branch}`, sha })
  if (!created.ok) fail(`branch ${branch} failed: ${describeFailure(created)}`)
}

async function upstreamDefaultBranch(repo) {
  const info = await api('GET', `/repos/${repo}`)
  return info.ok ? info.data.default_branch : 'main'
}

async function repoAgeHours() {
  const info = await api('GET', `/repos/${slug}`)
  return (Date.now() - Date.parse(info.data.created_at)) / 3_600_000
}

async function findIssue(repo, title) {
  const query = encodeURIComponent(`repo:${repo} in:title "${title}"`)
  const result = await api('GET', `/search/issues?q=${query}&per_page=10`)
  if (!result.ok) return undefined
  return result.data?.items?.find((issue) => issue.title === title && issue.pull_request === undefined)
}

function suiteTitle() {
  const text = readFileSync(join(submissions, 'dsh-suite-issue.md'), 'utf8')
  return text.split('\n')[0].replace(/^#\s+/u, '')
}

function suiteBody() {
  return readFileSync(join(submissions, 'dsh-suite-issue.md'), 'utf8').split('\n').slice(1).join('\n').trim()
}

function hubTitle() {
  return `[Plugin submission] ${slug} — ${listing.descriptions.headline.en}`
}

function hubBody() {
  const text = readFileSync(join(submissions, 'dsh-plugin-org.md'), 'utf8')
  const start = text.indexOf('## Body\n')
  if (start === -1) fail('dsh-plugin-org.md has no "## Body" section')
  return text.slice(start + '## Body\n'.length).trim()
}

function readTokenFile() {
  const path = join(homedir(), '.dsh-market-token')
  return existsSync(path) ? readFileSync(path, 'utf8').trim() : undefined
}

function makeApi(secret) {
  return async function request(method, path, body) {
    try {
      const response = await fetch(`https://api.github.com${path}`, {
        method,
        headers: {
          authorization: `Bearer ${secret}`,
          accept: 'application/vnd.github+json',
          'user-agent': 'harness-lingo-translator-market',
          ...(body === undefined ? {} : { 'content-type': 'application/json' }),
        },
        body: body === undefined ? undefined : JSON.stringify(body),
        signal: AbortSignal.timeout(30000),
      })
      const text = await response.text()
      let data
      try {
        data = text === '' ? undefined : JSON.parse(text)
      } catch {
        data = undefined
      }
      return { ok: response.ok, status: response.status, data, text }
    } catch (error) {
      return { ok: false, status: 0, data: undefined, text: String(error) }
    }
  }
}

function describeFailure(result) {
  const message = result.data?.message ?? result.text ?? 'unknown error'
  const details = result.data?.errors?.map((entry) => entry.message ?? entry.code).join('; ')
  return `HTTP ${String(result.status)} ${message}${details ? ` (${details})` : ''}`
}

function fail(message) {
  console.error(`submit-market: ${message}`)
  process.exit(1)
}
